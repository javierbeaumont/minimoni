/* Integration tests: our X.509 policy against the REAL br_x509_minimal engine, in process, with a
 * real certificate and no sockets. Run with: make test-integration.
 *
 * What this pins is an assumption about a vendored dependency that its docs do not promise: that an
 * unanchored, well-formed chain is reported as BR_ERR_X509_NOT_TRUSTED, and that get_pkey still
 * yields the key in that state. The whole https webhook path rests on it. When BearSSL is bumped, a
 * break here names the cause, where tests/e2e-webhook.sh would only report a lost delivery.
 *
 * Both certificates are generated by the Makefile, not committed: a stored valid one would expire
 * and silently turn into the expired case. */

